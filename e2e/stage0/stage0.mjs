function preflight() {
  const problems = []
  if (!existsSync(CLI)) {
    problems.push(`dsh 0.2.1 CLI not found at ${CLI}; set STAGE0_CLI to a dsh 0.2.1-era lib/bin.js`)
  }
  for (const packageName of ['harness2-task-recursion', 'harness2-meta-recursion']) {
    if (!existsSync(path.join(REPO, 'packages', packageName, 'lib', 'index.js'))) {
      problems.push(`missing build for ${packageName}; run: npm install && npm run build`)
    }
  }
  if (problems.length > 0) throw new Error(problems.join('\n'))
}

async function readExperienceEntries() {
  let text
  try {
    text = await readFile(EXPERIENCE, 'utf8')
  } catch {
    return { entries: [], markers: 0, parseErrors: 0 }
  }
  const pattern = /<!--\s*harness2-experience:([A-Za-z0-9+/=]+)\s*-->/g
  const matches = [...text.matchAll(pattern)]
  const entries = []
  let parseErrors = 0
  for (const match of matches) {
    try {
      entries.push(JSON.parse(Buffer.from(match[1], 'base64').toString('utf8')))
    } catch {
      parseErrors += 1
    }
  }
  return { entries, markers: matches.length, parseErrors }
}

