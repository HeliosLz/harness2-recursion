function pctOrDash(value) {
  return value === null || value === undefined ? '—' : `${(value * 100).toFixed(1)}%`
}

function sanitizeReport(report) {
  return report
    .split(REPO).join('<repo>')
    .split(CLI).join('<dsh-0.2.1-cli>')
    .split(HOME).join('<artifacts>/home')
    .split(DIR).join('e2e/stage0/artifacts')
}

function appendGraftSections(results) {
  const { summary, dualDenominator, experience, requestCorrelation, repoStatus } = results
  const lines = []
  lines.push('## Grafted checks (arena synthesis)')
  lines.push('')
  lines.push('### Dual denominator')
  lines.push('')
  lines.push('Primary rate uses compose cycles; the secondary rate uses attempted headless sessions.')
  lines.push('')
  lines.push('| Candidate | Accepted / sessions | Session rate | Accepted / compose cycles | Compose rate |')
  lines.push('| :-- | --: | --: | --: | --: |')
  for (const proposal of PROPOSALS) {
    const dual = dualDenominator[proposal.name]
    const primary = summary.perCandidate[proposal.name]
    lines.push(`| ${proposal.name} | ${dual.acceptedSessions} / ${dual.sessionsAttempted} | **${pctOrDash(dual.acceptanceRateBySession)}** | ${primary.accepted} / ${primary.denominator} | **${pctOrDash(primary.acceptanceRate)}** |`)
  }
  lines.push('')
  lines.push('### No-op sanity: the exact strings reached the wire')
  lines.push('')
  const badPropose = requestChecksSummary(requestCorrelation)
  lines.push(`- Propose requests observed: ${results.requestStats.byKind?.propose ?? '—'}; every logged Propose response contained **both** literal candidate strings: **${badPropose.proposeAllBoth ? 'yes' : 'no'}**.`)
  lines.push(`- Probe prompt coverage: **${badPropose.probeCovered} / ${requestCorrelation.length}** cycles had both literal candidate strings in their probe prompts.`)
  const first = requestCorrelation.find((cycle) => cycle.sessionIndex !== null) ?? null
  if (first !== null) {
    lines.push(`- Cycle 1 request window: ${JSON.stringify(first.byKind)} (expected { main: 4, propose: 1, probe: 2, reflection: 1 }).`)
  }
  lines.push('')
  lines.push('### Downstream: EXPERIENCE.md poisoning check')
  lines.push('')
  if (experience.entries === 0) {
    lines.push('- No experience entries were written (meta may be disabled or the reflection route failed); this is recorded as a gap, not a pass.')
  } else {
    lines.push(`- EXPERIENCE.md entries parsed: ${experience.markers} markers / ${experience.entries} valid (${experience.parseErrors} parse errors).`)
    for (const proposal of PROPOSALS) {
      const item = experience.byProposal[proposal.name]
      lines.push(`- ${proposal.name}: ${item.entries} entry/entries, accepted=${item.accepted}, rejected=${item.rejected}, hash \`${proposal.contentHash}\`.`)
    }
    const poisoned = experience.poisoned.filter((item) => item.acceptedInExperience).map((item) => item.name)
    lines.push(`- Accepted bad edits present as positive experience: **${poisoned.length === 0 ? 'none' : poisoned.join(', ')}**.`)
    lines.push('- NOTE: meta attributes one applied edit per event (`appliedEdits[0]`), so the other accepted candidate may be absent even though the gate accepted it; this asymmetry is recorded, not treated as a pass.')
  }
  lines.push('')
  lines.push('### Isolation: repo status before/after')
  lines.push('')
  lines.push(`- \`git status --porcelain\` (excluding \`e2e/stage0/\`) unchanged during the run: **${repoStatus.changed ? 'no' : 'yes'}**.`)
  if (repoStatus.before.lines?.length > 0) {
    lines.push(`- Pre-existing dirty lines (not caused by this run): \`${repoStatus.before.lines.join(' ; ')}\``)
  }
  lines.push('')
  lines.push('### Per-cycle fake-server correlation')
  lines.push('')
  lines.push('| Cycle | Session | main | propose | probe | reflection | propose literals | probe literals |')
  lines.push('| --: | --: | --: | --: | --: | --: | :--: | :--: |')
  for (const cycle of requestCorrelation) {
    const proposeBoth = PROPOSALS.every((proposal) => cycle.proposeCoverage[proposal.name])
    const probeBoth = PROPOSALS.every((proposal) => cycle.probeCoverage[proposal.name])
    lines.push(`| ${cycle.cycleIndex} | ${cycle.sessionIndex ?? '—'} | ${cycle.byKind.main ?? 0} | ${cycle.byKind.propose ?? 0} | ${cycle.byKind.probe ?? 0} | ${cycle.byKind.reflection ?? 0} | ${proposeBoth ? 'yes' : 'NO'} | ${probeBoth ? 'yes' : 'NO'} |`)
  }
  lines.push('')
  return lines.join('\n')
}

function requestChecksSummary(requestCorrelation) {
  const withSession = requestCorrelation.filter((cycle) => cycle.sessionIndex !== null)
  return {
    proposeAllBoth: (withSession.length > 0 && withSession.every((cycle) =>
      PROPOSALS.every((proposal) => cycle.proposeCoverage[proposal.name]))),
    probeCovered: withSession.filter((cycle) =>
      PROPOSALS.every((proposal) => cycle.probeCoverage[proposal.name])).length,
    total: withSession.length,
  }
}

let server = null

async function main() {
  log(`Stage-0 falsification starting (${CYCLES} cycles, port ${PORT})`)
  preflight()
  await mkdir(DIR, { recursive: true })
  await mkdir(SESSIONS_DIR, { recursive: true })

  const repoStatusBefore = gitStatusFiltered()
  const setup = await setupProfile()
  log('profile composed and both bundles installed')

  // Fresh measurement artifacts: the ledger must contain exactly this run.
  await rm(LEDGER, { force: true })
  await rm(EXPERIENCE, { force: true })
  await rm(REQUESTS, { force: true })

  server = await startFakeServer()
  log('fake server ready')

  const sessions = []
  for (let index = 1; index <= CYCLES; index += 1) {
    sessions.push(await runOneSession(index))
  }

  await sleep(500)
  const repoStatusAfter = gitStatusFiltered()
  const records = await readJsonl(LEDGER)
  const requestLog = await readJsonl(REQUESTS)
  const experienceData = await readExperienceEntries()
  const elapsedMs = Date.now() - STARTED_AT
  log(`collected ${records.length} ledger records; analyzing`)

  const results = analyze(
    records, sessions, setup, server, elapsedMs, requestLog,
    experienceData, repoStatusBefore, repoStatusAfter,
  )
  await writeFile(RESULTS, `${JSON.stringify(results, null, 2)}\n`, 'utf8')
  const report = `${buildReport(results)}\n${appendGraftSections(results)}`
  await writeFile(REPORT, report, 'utf8')
  await writeFile(RESULTS_MD, sanitizeReport(report), 'utf8')

  log(`status=${results.summary.status} verdict=${results.summary.verdict}`)
  log(`NULL ${pct(results.summary.perCandidate['null-edit'].acceptanceRate)} (${results.summary.perCandidate['null-edit'].accepted}/${results.summary.perCandidate['null-edit'].denominator}); ADVERSARIAL ${pct(results.summary.perCandidate['adversarial-edit'].acceptanceRate)} (${results.summary.perCandidate['adversarial-edit'].accepted}/${results.summary.perCandidate['adversarial-edit'].denominator})`)
  log(`wrote ${RESULTS} and ${REPORT} in ${(elapsedMs / 1000).toFixed(1)}s`)
}

try {
  await main()
} catch (error) {
  const elapsedMs = Date.now() - STARTED_AT
  const message = error instanceof Error ? `${error.message}\n${error.stack ?? ''}` : String(error)
  log(`FAILED: ${message}`)
  try {
    await writeFile(
      RESULTS,
      `${JSON.stringify({
        experiment: {
          name: 'stage0-compose-rubber-stamp',
          status: 'BLOCKED',
          startedAt: new Date(STARTED_AT).toISOString(),
          finishedAt: new Date().toISOString(),
          elapsedMs,
          error: message,
        },
      }, null, 2)}\n`,
      'utf8',
    )
    await writeFile(
      REPORT,
      `# Stage-0 falsification report — BLOCKED\n\nStatus: **BLOCKED**\n\nElapsed: ${(elapsedMs / 1000).toFixed(1)}s\n\n\`\`\`\n${message}\n\`\`\`\n`,
      'utf8',
    )
  } catch {
    // Nothing else to write; the process exit code carries the failure.
  }
  process.exitCode = 1
} finally {
  if (server !== null) {
    try {
      await server.stop()
      log('fake server stopped')
    } catch (error) {
      log(`failed to stop fake server: ${error instanceof Error ? error.message : String(error)}`)
    }
  }
}
