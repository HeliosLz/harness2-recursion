/**
 * Round-6 feasibility spike — offline profile-patch closed loop (no upstream API).
 *
 * Proves, against a real dsh 0.2.1-rc.2 runtime in an isolated DSH_HOME:
 *   1. a candidate edit can be rendered as a profile `cordis.patch.yml` override
 *      for a real artifact (dsh-system-prompt personaPrefix) and written atomically;
 *   2. the next launch composes the new value (restart reload; headless disables HMR);
 *   3. a byte-restored backup (one-command rollback) composes the old value again;
 *   4. no repo file is touched.
 *
 * Usage: node run-spike.mjs
 */
import { spawn, spawnSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { closeSync, fsyncSync, openSync, readFileSync, writeFileSync } from 'node:fs'
import { copyFile, mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const REPO = path.resolve(HERE, '..', '..')
const CLI = process.env.SPIKE_CLI ?? '/tmp/dsh021/dsh/node_modules/@deepseek-ai/dsh/lib/bin.js'
const HOME = path.join(HERE, 'artifacts', 'home')
const ART = path.join(HERE, 'artifacts')
const PROFILE = 'r6spike'
const PROFILE_DIR = path.join(HOME, 'profiles', PROFILE)
const PATCH = path.join(PROFILE_DIR, 'cordis.patch.yml')
const BACKUP = path.join(PROFILE_DIR, 'cordis.patch.yml.r6-backup')
const PORT = Number(process.env.SPIKE_PORT ?? 8899)
const LOG = path.join(ART, 'requests.jsonl')
const REPORT = path.join(ART, 'SPIKE-RESULTS.json')

const gitDirty = () => {
  const run = spawnSync('git', ['status', '--porcelain'], { cwd: REPO, encoding: 'utf8' })
  return (run.stdout ?? '').split('\n').map((line) => line.trimEnd()).filter(Boolean)
}
const repoDirtyBefore = gitDirty()

const results = { steps: [], assertions: [] }
const check = (name, ok, detail) => {
  results.assertions.push({ name, ok, detail })
  if (!ok) throw new Error(`ASSERTION FAILED: ${name} (${JSON.stringify(detail ?? null)})`)
}
const sha256 = (value) => createHash('sha256').update(value, 'utf8').digest('hex')
const fileHash = async (file) => `sha256:${sha256(await readFile(file, 'utf8'))}`
const log = (message) => { results.steps.push(message); console.log(`- ${message}`) }

function cli(args, env = {}) {
  const run = spawnSync(process.execPath, [CLI, ...args], {
    encoding: 'utf8',
    env: { ...process.env, DSH_HOME: HOME, ...env },
    timeout: 240_000,
  })
  if (run.status !== 0) throw new Error(`CLI failed (${args.join(' ')}):\n${run.stdout}\n${run.stderr}`)
  return run.stdout ?? ''
}

/** Atomic same-directory write: tmp -> fsync -> rename -> fsync(dir). */
async function atomicWrite(file, text) {
  const tmp = `${file}.tmp-${process.pid}-${Date.now()}`
  const fd = openSync(tmp, 'w')
  try { writeFileSync(fd, text, 'utf8'); fsyncSync(fd) } finally { closeSync(fd) }
  const { rename } = await import('node:fs/promises')
  await rename(tmp, file)
  const dirFd = openSync(path.dirname(file), 'r')
  try { fsyncSync(dirFd) } finally { closeSync(dirFd) }
}

/** The R6 renderer under test: complete row config replacement, not a merge. */
function renderPatch({ personaPrefix }) {
  return `# Generated by the Round-6 offline applier (spike). Row "system-prompt"
# replaces the whole config, so every key the renderer does not intend to change
# is restated from the composed view.
- id: agent-default-model
  name: '@deepseek-ai/dsh-agent-default-model'
  config:
    provider: faketest
    model: spike-model
- id: llm-pi-ai
  name: '@deepseek-ai/dsh-llm-pi-ai'
  config:
    providers:
      faketest:
        displayName: Fake Test
        api: openai-completions
        baseURL: http://127.0.0.1:${PORT}/v1
        apiKeyEnv: FAKE_API_KEY
        models:
          - id: spike-model
            name: Spike Model
            contextWindow: 200000
            reasoningEfforts: false
- id: session-title-llm
  disabled: true
- id: system-prompt
  config:
    includeHarnessIdentity: true
    includeRuntimeContext: true
    personaPrefix: '${personaPrefix}'
- id: harness2-task-recursion
  name: harness2-task-recursion
  config:
    ledgerPath: ${path.join(ART, 'ledger.jsonl')}
    observeOnly: true
- id: harness2-meta-recursion
  name: harness2-meta-recursion
  config:
    experiencePath: ${path.join(ART, 'EXPERIENCE.md')}
`
}

async function lineCount() {
  try { return (await readFile(LOG, 'utf8')).trim().split('\n').filter(Boolean).length } catch { return 0 }
}

async function runSession(label, task) {
  const before = await lineCount()
  const server = spawn(process.execPath, [path.join(HERE, 'fake-openai.mjs')], {
    env: { ...process.env, SPIKE_PORT: String(PORT), SPIKE_LOG: LOG },
    stdio: ['ignore', 'pipe', 'pipe'],
  })
  await new Promise((resolve, reject) => {
    const timer = setTimeout(() => reject(new Error('fake provider did not start')), 5000)
    server.stdout.once('data', () => { clearTimeout(timer); resolve() })
    server.once('error', reject)
  })
  try {
    const run = spawnSync(process.execPath, [CLI, '--profile', PROFILE, task], {
      encoding: 'utf8',
      env: { ...process.env, DSH_HOME: HOME, FAKE_API_KEY: 'dummy' },
      timeout: 180_000,
    })
    check(`${label}: session exits 0`, run.status === 0, { status: run.status, stderr: run.stderr?.slice(0, 600) })
    const lines = (await readFile(LOG, 'utf8')).trim().split('\n').filter(Boolean).slice(before)
    const wire = lines.join('\n')
    results.steps.push(`${label}: ${lines.length} provider requests`)
    return wire
  } finally {
    server.kill('SIGTERM')
    await new Promise((resolve) => setTimeout(resolve, 150))
  }
}

await rm(path.join(ART, 'home'), { recursive: true, force: true })
await rm(LOG, { force: true })
await mkdir(ART, { recursive: true })

log('create isolated headless profile')
cli(['--profile', PROFILE, '--from-default-profile', 'headless', '--dump-config'])

log('install both bundles through the official CLI path')
for (const dir of ['harness2-task-recursion', 'harness2-meta-recursion']) {
  cli(['plugin', '--profile', PROFILE, 'add', path.join(REPO, 'packages', dir)])
}

log('revision A: render + atomic write (backup first)')
const patchA = renderPatch({ personaPrefix: 'SPIKE-PERSONA-ALPHA You are a coding agent.' })
await writeFile(PATCH, patchA, 'utf8')
await copyFile(PATCH, BACKUP)
const hashA = await fileHash(PATCH)
await mkdir(path.join(ART, 'revisions', 'rev-A', 'backup'), { recursive: true })
await copyFile(PATCH, path.join(ART, 'revisions', 'rev-A', 'backup', 'cordis.patch.yml'))
const dumpA = cli(['--profile', PROFILE, '--dump-config'])
check('dump-config composes revision A persona', dumpA.includes('SPIKE-PERSONA-ALPHA'), null)

const wireA = await runSession('session-A', 'Spike A: answer with one sentence about latency.')
check('revision A reached the model wire', wireA.includes('SPIKE-PERSONA-ALPHA'), null)

log('revision B: render + atomic write (backup kept)')
const patchB = renderPatch({ personaPrefix: 'SPIKE-PERSONA-BETA You are a terse coding agent.' })
await atomicWrite(PATCH, patchB)
const hashB = await fileHash(PATCH)
check('write is byte-observable and hash differs', hashA !== hashB, { hashA, hashB })
const dumpB = cli(['--profile', PROFILE, '--dump-config'])
check('dump-config composes revision B persona', dumpB.includes('SPIKE-PERSONA-BETA'), null)

const wireB = await runSession('session-B', 'Spike B: answer with one sentence about retries.')
check('revision B reached the model wire', wireB.includes('SPIKE-PERSONA-BETA'), null)
check('revision A no longer on the wire', !wireB.includes('SPIKE-PERSONA-ALPHA'), null)

log('rollback: restore backup bytes atomically')
const backupBytes = await readFile(path.join(ART, 'revisions', 'rev-A', 'backup', 'cordis.patch.yml'), 'utf8')
await atomicWrite(PATCH, backupBytes)
const hashRollback = await fileHash(PATCH)
check('rollback restores revision A bytes exactly', hashRollback === hashA, { hashRollback, hashA })

const wireC = await runSession('session-C', 'Spike C: answer with one sentence about recovery.')
check('rollback reached the model wire', wireC.includes('SPIKE-PERSONA-ALPHA'), null)
check('rollback removed revision B from the wire', !wireC.includes('SPIKE-PERSONA-BETA'), null)

log('repo untouched check (spike only reads the repo as a plugin source)')
const repoDirtyAfter = gitDirty()
const newDirty = repoDirtyAfter.filter((line) => !repoDirtyBefore.includes(line))
check('spike did not modify the repo (dirty set unchanged)', newDirty.length === 0, { before: repoDirtyBefore, after: repoDirtyAfter })

results.verdict = 'PASS'
await writeFile(REPORT, `${JSON.stringify(results, null, 2)}\n`, 'utf8')
console.log(`\nPASS — ${results.assertions.length} assertions; report: ${REPORT}`)
