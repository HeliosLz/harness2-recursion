/**
 * Round-5 real-session E2E runner.
 *
 * Prerequisites: a dsh 0.2.1-rc.2 CLI runtime (default path: the extracted app
 * runtime). The script creates an isolated DSH_HOME, installs both bundles via
 * `dsh plugin add`, points a fake OpenAI-compatible provider at e2e/fake-model-server.mjs,
 * runs TWO one-shot headless sessions (fresh ledger → noop-todo, then
 * next-task-ledger), and asserts ledger/experience/applyMode behavior.
 *
 * Usage:
 *   E2E_CLI=/tmp/dsh021/dsh/node_modules/@deepseek-ai/dsh/lib/bin.js \
 *   node e2e/run.mjs
 */
import { spawn, spawnSync } from 'node:child_process'
import { existsSync } from 'node:fs'
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const artifacts = path.join(repoRoot, 'e2e', 'artifacts')
const ledgersPath = path.join(artifacts, 'ledger.jsonl')
const experiencePath = path.join(artifacts, 'EXPERIENCE.md')
const cli = process.env.E2E_CLI ?? '/tmp/dsh021/dsh/node_modules/@deepseek-ai/dsh/lib/bin.js'
const dshHome = process.env.E2E_HOME ?? '/tmp/h2-e2e-run'
const profile = 'h2e2e'
const port = Number(process.env.E2E_PORT ?? 8791)
const profileDir = path.join(dshHome, 'profiles', profile)
const pluginDirs = [
  path.join(repoRoot, 'packages', 'harness2-task-recursion'),
  path.join(repoRoot, 'packages', 'harness2-meta-recursion'),
]

function runCli(args, env = {}) {
  const result = spawnSync(process.execPath, [cli, ...args], {
    encoding: 'utf8',
    env: { ...process.env, DSH_HOME: dshHome, ...env },
    timeout: 180_000,
  })
  if (result.status !== 0) {
    throw new Error(`CLI failed (${args.join(' ')}):\n${result.stderr ?? ''}\n${result.stdout ?? ''}`)
  }
  return result.stdout ?? ''
}

function assert(condition, message) {
  if (!condition) throw new Error(`ASSERTION FAILED: ${message}`)
}

if (!existsSync(cli)) {
  console.error(`dsh CLI runtime not found at ${cli}; set E2E_CLI to a 0.2.1-era dsh bin.js`)
  process.exit(2)
}

await rm(dshHome, { recursive: true, force: true })
await rm(artifacts, { recursive: true, force: true })
await mkdir(artifacts, { recursive: true })
await mkdir(dshHome, { recursive: true })

// 1. Create the isolated headless profile.
runCli(['--profile', profile, '--from-default-profile', 'headless', '--dump-config'])

// 2. Install both bundles through the official CLI path.
for (const dir of pluginDirs) runCli(['plugin', '--profile', profile, 'add', dir])
const profilePackage = JSON.parse(await readFile(path.join(profileDir, 'package.json'), 'utf8'))
const installed = Object.keys(profilePackage.dependencies ?? {})
assert(installed.includes('dsh-harness2-task-recursion'), 'task plugin installed')
assert(installed.includes('dsh-harness2-meta-recursion'), 'meta plugin installed')

// 3. Point the profile at the fake provider and configure both plugins.
await writeFile(path.join(profileDir, 'cordis.patch.yml'), `# Generated by e2e/run.mjs
- id: agent-default-model
  name: '@deepseek-ai/dsh-agent-default-model'
  config:
    provider: faketest
    model: main-model
- id: llm-pi-ai
  name: '@deepseek-ai/dsh-llm-pi-ai'
  config:
    providers:
      faketest:
        displayName: Fake Test
        api: openai-completions
        baseURL: http://127.0.0.1:${port}/v1
        apiKeyEnv: FAKE_API_KEY
        retryPolicy:
          mode: always
          backoff:
            initialDelayMs: 200
            maxDelayMs: 2000
            jitterRatio: 0
        models:
          - id: main-model
            name: Main Model
            contextWindow: 200000
            reasoningEfforts: false
          - id: propose-model
            name: Propose Model
            contextWindow: 200000
            reasoningEfforts: false
- id: session-title-llm
  disabled: true
- id: harness2-task-recursion
  name: dsh-harness2-task-recursion
  config:
    ledgerPath: ${ledgersPath}
    observeOnly: false
    gatePolicy: v3
    proposeModel: faketest/propose-model
    maxCostPerCycle: 500000
    probeTimeoutMs: 60000
    triggerThreshold: 3
    repeatedFailureWindow: 3
    cooldownMs: 0
- id: harness2-meta-recursion
  name: dsh-harness2-meta-recursion
  config:
    experiencePath: ${experiencePath}
    llmReflectionModel: faketest/propose-model
    minConfidenceToInject: 0.4
    minNegativeConfidenceToInject: 0.3
`, 'utf8')

// 4. Confirm the composed profile contains both plugin rows and configs.
const dump = runCli(['--profile', profile, '--dump-config'])
for (const needle of [
  'harness2-task-recursion',
  'harness2-meta-recursion',
  `ledgerPath: ${ledgersPath}`,
  `experiencePath: ${experiencePath}`,
]) {
  assert(dump.includes(needle), `dump-config contains ${needle}`)
}

// 5. Run two real sessions: fresh ledger then revision-aware run.
const tasks = [
  'Investigate the failing command and report the result.',
  'Re-run the same failing command and report the result.',
]
const runSummaries = []
for (const [index, task] of tasks.entries()) {
  const server = spawn(process.execPath, [path.join(repoRoot, 'e2e', 'fake-model-server.mjs')], {
    env: {
      ...process.env,
      FAKE_PORT: String(port),
      FAKE_FAILURES: '3',
      FAKE_SLOW_MS: '6000',
      FAKE_LOG: path.join(artifacts, `fake-requests-run${index + 1}.jsonl`),
    },
    stdio: ['ignore', 'pipe', 'pipe'],
  })
  await new Promise((resolve, reject) => {
    const timer = setTimeout(() => reject(new Error('fake server did not start')), 5000)
    server.stdout.once('data', () => {
      clearTimeout(timer)
      resolve()
    })
    server.once('error', reject)
  })
  try {
    const result = spawnSync(
      process.execPath,
      [cli, '--profile', profile, task],
      {
        encoding: 'utf8',
        env: { ...process.env, DSH_HOME: dshHome, FAKE_API_KEY: 'dummy' },
        timeout: 180_000,
      },
    )
    assert(result.status === 0, `session ${index + 1} exits 0 (stderr: ${result.stderr})`)
    assert((result.stdout ?? '').includes('E2E FINAL'), `session ${index + 1} printed the final answer`)
    runSummaries.push({ task, stdout: result.stdout.trim() })
  } finally {
    server.kill('SIGTERM')
    await new Promise((resolve) => setTimeout(resolve, 200))
  }
}

// 6. Verify the ledger and experience library.
const ledgerLines = (await readFile(ledgersPath, 'utf8')).trim().split('\n').filter(Boolean)
const records = ledgerLines.map((line) => JSON.parse(line))
assert(records.length === 4, `two cycles produce four v3 records (got ${records.length})`)
assert(records.every((record) => record.version === 'harness2-ledger/v3'), 'all records are ledger v3')
assert(
  records.every((record) => typeof record.id === 'string'
    && typeof record.recordedAt === 'string'
    && 'previousSnapshotRef' in record
    && record.ledgerEntryId === record.id),
  'v3 envelope fields are complete',
)
assert(records[0].event === 'probe/completed' && records[1].event === 'compose/applied', 'run1 event order')
assert(records[2].event === 'probe/completed' && records[3].event === 'compose/applied', 'run2 event order')
assert(records[0].payload.trials.every((trial) => trial.valid && trial.metrics.tokenCostSource === 'measured'), 'real tokenMeter measurement')
assert(records[1].payload.applyMode === 'noop-todo', 'first run degrades to noop-todo (no ledger at activation)')
assert(records[3].payload.applyMode === 'next-task-ledger', 'second run detects the ledger revision path')
assert(records[2].previousSnapshotRef === records[1].id, 'second task anchors on the previous run revision')
assert(records[1].payload.previousSnapshotRef === records[0].id, 'probe record anchors the applied edit')
const appliedEdits = records[1].payload.appliedEdits
const trialHashes = new Map(records[0].payload.trials.map((trial) => [trial.candidateId, trial.editContentHash]))
assert(appliedEdits.length > 0, 'appliedEdits is non-empty')
for (const edit of appliedEdits) {
  assert(trialHashes.get(edit.candidateId) === edit.contentHash, `edit hash matches trial fact for ${edit.candidateId}`)
}
// PR-5: compose/* is diagnostic only; a compose cycle must not create experience.
// Verified experience requires a real-provider evaluation index/report, which
// this round-5 E2E does not produce.
const experienceText = await readFile(experiencePath, 'utf8').catch(() => '')
const entryCount = (experienceText.match(/harness2-experience:/g) ?? []).length
assert(entryCount === 0, 'PR-5: compose/applied must not write EXPERIENCE.md')

// 7. Persist a human-readable result.
const summary = [
  '# Round-5 real-session E2E result',
  '',
  `- CLI: \`${cli}\``,
  `- DSH_HOME: \`${dshHome}\` (isolated profile \`${profile}\`)`,
  `- Plugin rows in composed profile: ✅ (dump-config checked)`,
  `- Sessions: ${runSummaries.length} (exit 0, final answer printed)`,
  `- Ledger: ${records.length} v3 records (2 probe/completed + 2 compose/applied)`,
  `- applyMode: run1=${records[1].payload.applyMode}, run2=${records[3].payload.applyMode}`,
  `- Revision anchor chain: ${records.map((record) => record.previousSnapshotRef ?? 'null').join(' -> ')}`,
  `- EXPERIENCE.md entries: ${entryCount} (PR-5: compose is diagnostic only)`,
  `- Token measurement: measured (tokenMeter)`,
  '',
  '## Session outputs',
  ...runSummaries.map((run, index) => `- session ${index + 1}: ${run.stdout}`),
  '',
]
await writeFile(path.join(artifacts, 'RESULTS.md'), summary.join('\n'), 'utf8')
console.log(summary.join('\n'))
console.log(`artifacts: ${artifacts}`)
